export function income90(value){
 if(value===''||value===undefined||value===null)return {error:'원 단위 세전 수입을 입력하세요.'};
 const gross=Number(value);
 if(!Number.isSafeInteger(gross)||gross<0||gross>999999999999)return {error:'0 이상의 원 단위 금액을 입력하세요.'};
 // Compare before rounding. 2,777,777 × 0.9 must not be rounded up to eligibility.
 const scaled=gross*9, income=scaled/10;
 return {gross,income,band:scaled>=25000000?'high':scaled>=7000000?'middle':'low',text:`세전 수입 ${won(gross)} × 90% = 판단 소득 ${won(income)}`};
}
